/**
 * EP34 — โครงสร้างกรณีศึกษาจริง (ยังไม่เผยแพร่)
 *
 * เพิ่มรายการได้เฉพาะกรณีจริงที่ผ่านการยืนยันเท่านั้น:
 * - A: ข้อเท็จจริงที่ยืนยันแล้ว · B: กรณีจริงแบบไม่ระบุตัวตน · C: ต้องได้รับอนุญาตจากลูกค้าก่อน (ห้ามเผยแพร่จนกว่าจะได้รับอนุญาต)
 * - D: ตัวอย่างสมมติ ห้ามใส่ในไฟล์นี้ (ใช้ data/scenarios.ts และติดป้าย "สถานการณ์สมมติ")
 * ห้ามใส่ตัวเลขผลลัพธ์ที่ไม่ได้ยืนยัน ชื่อหรือโลโก้ลูกค้าที่ไม่ได้รับอนุญาต หรือคำรับรองที่ไม่มีต้นฉบับจริง
 * เมื่อรายการว่าง ส่วนแสดงผลจะไม่แสดงบนเว็บไซต์ และยังไม่สร้างหน้า /case-studies
 */
export interface CaseStudy {
  id: string;
  /** ประเภทธุรกิจ (ไม่ระบุตัวตนได้) */
  context: string;
  /** สถานการณ์จริงก่อนเริ่มงาน */
  situation: string;
  /** งานที่ S2 ทำจริง */
  work: string[];
  /** ผลที่สังเกตได้ (ระดับ 2–3) */
  outcome: string;
  /** ผลเชิงตัวเลข เฉพาะที่ยืนยันแล้ว (ระดับ 1) */
  verifiedMetric?: string;
  /** slug บริการที่เกี่ยวข้อง */
  services: string[];
  /** ได้รับอนุญาตให้เผยแพร่ชื่อลูกค้าหรือไม่ */
  clientNamePermitted: boolean;
  clientName?: string;
}

export const caseStudies: CaseStudy[] = [];
